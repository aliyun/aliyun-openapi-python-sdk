from aliyunsdkcore.request import RpcRequest
from aliyunsdkgpdb.endpoint import endpoint_data
import json

class CreateApiKeyRequest(RpcRequest):

	def __init__(self):
		RpcRequest.__init__(self, 'gpdb', '2016-05-03', 'CreateApiKey','GPDB')
		self.set_protocol_type('https')
		self.set_method('POST')

		if hasattr(self, "endpoint_map"):
			setattr(self, "endpoint_map", endpoint_data.getEndpointMap())
		if hasattr(self, "endpoint_regional"):
			setattr(self, "endpoint_regional", endpoint_data.getEndpointRegional())

	def get_Description(self): # String
		return self.get_query_params().get('Description')

	def set_Description(self, Description):  # String
		self.add_query_param('Description', Description)
	def get_ServiceIds(self): # Array
		return self.get_query_params().get('ServiceIds')

	def set_ServiceIds(self, ServiceIds):  # Array
		self.add_query_param("ServiceIds", json.dumps(ServiceIds))
	def get_KeyName(self): # String
		return self.get_query_params().get('KeyName')

	def set_KeyName(self, KeyName):  # String
		self.add_query_param('KeyName', KeyName)
	def get_WorkspaceId(self): # String
		return self.get_query_params().get('WorkspaceId')

	def set_WorkspaceId(self, WorkspaceId):  # String
		self.add_query_param('WorkspaceId', WorkspaceId)
